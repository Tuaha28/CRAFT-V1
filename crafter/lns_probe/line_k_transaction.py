def _local_machine_check(problem, index, mutable, cp_assignment):
    """Verify selected IDs against frozen and local machine boundaries."""
    outside = outside_machine_reservations(problem, index, mutable)
    rows_by_machine = defaultdict(list)
    failures = []
    for key in sorted(mutable):
        operation = problem.operation_by_key[key]
        item = cp_assignment[key]
        machine_ids = tuple(sorted(int(v) for v in item.get("machine_ids", ())))
        if len(machine_ids) != int(item["machine_count"]):
            failures.append({"operation_key": key, "reason": "wrong machine count",
                             "required": item["machine_count"], "actual": list(machine_ids)})
            continue
        if int(item["line_id"]) not in operation.eligible_line_ids:
            failures.append({"operation_key": key, "reason": "illegal line"})
        for machine_id in machine_ids:
            machine = problem.machine_by_id.get(machine_id)
            if not (machine and machine.is_usable and
                    machine.factory_id == problem.order_by_id[operation.order_id].factory_id and
                    machine.line_id == int(item["line_id"]) and
                    machine.supports(operation.required_capability)):
                failures.append({"operation_key": key, "machine_id": machine_id,
                                 "reason": "physical machine eligibility"})
                continue
            if not _machine_accepts(outside.get(machine_id, ()),
                                    int(item["start_seconds"]), int(item["end_seconds"]),
                                    operation.order_id):
                failures.append({"operation_key": key, "machine_id": machine_id,
                                 "reason": "outside machine boundary"})
            rows_by_machine[machine_id].append((
                int(item["start_seconds"]), int(item["end_seconds"]),
                operation.order_id, key))
    for machine_id, rows in rows_by_machine.items():
        rows.sort(key=lambda v: (v[0], v[1], v[3]))
        for left, right in zip(rows, rows[1:]):
            required = authoritative_changeover_seconds(left[2], right[2])
            if left[1] + required > right[0]:
                failures.append({"machine_id": machine_id, "left": left[3],
                                 "right": right[3], "reason": "local transition",
                                 "required_gap": required,
                                 "available_gap": right[0]-left[1]})
    return failures


def _allocate_workers(problem, operator_index, op_details, index, mutable,
                      cp_assignment):
    reservations = _outside_worker_state(problem, index, mutable)
    busy = None
    realized = {}
    envelope_deltas = {}
    ordered = sorted(mutable, key=lambda key: (
        int(cp_assignment[key]["productive_start_seconds"]),
        problem.operation_by_key[key].sequence, key))
    failures = []
    for key in ordered:
        operation = problem.operation_by_key[key]
        item = cp_assignment[key]
        k = int(item["machine_count"])
        _setup, productive = authoritative_operation_work_minutes(op_details[key], k)
        ready = problem.origin + timedelta(seconds=int(item["productive_start_seconds"]))
        # The CP option was generated by the existing authoritative allocator
        # against the frozen worker state.  Recheck that exact crew here after
        # earlier local operations have been reserved.  This keeps worker
        # identity deterministic while still preserving the production
        # calendar/pause primitive, rather than treating labour as a
        # continuous interval.
        preview_workers = tuple(str(v) for v in item.get("preview_worker_ids", ()))
        used_fixed = bool(preview_workers) and len(preview_workers) == k
        if used_fixed:
            def available(when):
                return all(operator_available_at(
                    operator_index, int(employee) if str(employee).isdigit() else employee,
                    when) and all(not (left <= when < right)
                                  for left, right in reservations.get(str(employee), ()))
                           for employee in preview_workers)
            def next_change(when):
                values = []
                for employee in preview_workers:
                    for left, right in reservations.get(str(employee), ()):
                        if left > when:
                            values.append(left)
                        if right > when:
                            values.append(right)
                return min(values) if values else None
            _start, end_dt, segments = walk_fixed_crew(
                ready, productive, available, next_availability_change=next_change)
            actual_end = int(round((end_dt-problem.origin).total_seconds()))
            selected_workers = preview_workers
            tier = str(item.get("preview_tier", "authoritative_preview"))
            for employee in selected_workers:
                employee_key = str(employee)
                reservations[employee_key] = _merge_reserved_segments(
                    reservations.get(employee_key, ()), segments)
            busy = dict(busy or reservation_busy_minutes(reservations))
            for employee in selected_workers:
                busy[str(employee)] = busy.get(str(employee), 0.0) + float(productive)
            result = {"employees": selected_workers, "segments": tuple(segments),
                      "tier": tier, "end": end_dt,
                      "reservations": reservations, "busy_minutes": busy}
        else:
            result = allocate_crew(
                operator_index, operation.required_capability, int(item["line_id"]),
                k, ready, productive, reservations, busy, priority=0.5,
                state_is_normalized=True)
            if result.get("shortage") is not None:
                failures.append({"operation_key": key, "reason": "worker allocation",
                                 "detail": result.get("shortage")})
                return {"success": False, "failures": failures}, None
            actual_end = int(round((result["end"]-problem.origin).total_seconds()))
            selected_workers = tuple(str(v) for v in result["employees"])
        realized[key] = {
            "employees": selected_workers,
            "segments": tuple(result["segments"]),
            "tier": result["tier"],
            "end_seconds": actual_end,
            "productive_minutes": float(productive),
        }
        preview_end = int(item.get("end_seconds", actual_end))
        envelope_deltas[key] = {
            "preview_end_seconds": preview_end,
            "realized_end_seconds": actual_end,
            "extension_seconds": actual_end - preview_end,
            "preview_worker_ids": [str(v) for v in item.get("preview_worker_ids", ())],
            "realized_worker_ids": [str(v) for v in selected_workers],
        }
        reservations, busy = result["reservations"], result["busy_minutes"]
    return {"success": True, "operations": len(realized), "failures": failures,
            "envelope_deltas": envelope_deltas}, realized


def realize_line_k_transaction(problem, operator_index, op_details, index,
                               mutable_keys, cp_assignment, baseline):
    mutable = set(mutable_keys)
    baseline_by_key = {item.assignment.operation_key: item for item in baseline.operations}
    machine_failures = _local_machine_check(problem, index, mutable, cp_assignment)
    if machine_failures:
        return {"accepted": False, "stage": "machine", "machine_verification_success": False,
                "machine_failures": machine_failures, "worker_feasible": None,
                "rollback_hash": baseline.phenotype_hash}, None

    worker_result, workers = _allocate_workers(problem, operator_index, op_details,
                                               index, mutable, cp_assignment)
    if not worker_result["success"]:
        return {"accepted": False, "stage": "worker", "machine_verification_success": True,
                "machine_failures": [], "worker_feasible": False,
                "worker_failures": worker_result["failures"],
                "envelope_deltas": worker_result.get("envelope_deltas", {}),
                "rollback_hash": baseline.phenotype_hash}, None

    # Worker calendars can extend the CP envelope.  Recheck exact selected
    # machines with the realized elapsed end before materializing a phenotype.
    realized_assignment = {key: dict(value) for key, value in cp_assignment.items()}
    for key, result in workers.items():
        realized_assignment[key]["end_seconds"] = int(result["end_seconds"])
    machine_failures = _local_machine_check(problem, index, mutable,
                                            realized_assignment)
    if machine_failures:
        return {"accepted": False, "stage": "worker_machine_envelope",
                "machine_verification_success": False,
                "machine_failures": machine_failures, "worker_feasible": False,
                "worker_failures": [{"reason": "worker extension invalidates machine envelope"}],
                "envelope_deltas": worker_result.get("envelope_deltas", {}),
                "rollback_hash": baseline.phenotype_hash}, None

    operations = []
    for operation in problem.operations:
        key = operation.operation_key
        if key not in mutable:
            operations.append(baseline_by_key[key])
            continue
        cp = realized_assignment[key]
        worker = workers[key]
        assignment = OperationAssignment(
            operation_key=key, order_id=operation.order_id,
            operation_id=operation.operation_id, line_id=int(cp["line_id"]),
            machine_ids=tuple(sorted(int(v) for v in cp["machine_ids"])),
            machine_count=int(cp["machine_count"]),
            start_seconds=int(cp["start_seconds"]),
            productive_start_seconds=int(cp["productive_start_seconds"]),
            end_seconds=int(worker["end_seconds"]),
            setup_seconds=int(cp["setup_seconds"]),
            productive_seconds=int(cp["productive_seconds"]),
        )
        operations.append(PhenotypeOperation(
            assignment=assignment, employee_ids=tuple(worker["employees"]),
            worker_segments=tuple((employee, tuple(worker["segments"]))
                                  for employee in worker["employees"]),
            sourcing_tier=worker["tier"],
        ))
    candidate = CrafterPhenotype(CrafterStatus.WORKER_FEASIBLE, tuple(operations))
    outside_unchanged = all(
        baseline_by_key[key] == next(item for item in candidate.operations
                                     if item.assignment.operation_key == key)
        for key in baseline_by_key if key not in mutable)
    if not outside_unchanged:
        return {"accepted": False, "stage": "identity",
                "machine_verification_success": True, "worker_feasible": True,
                "outside_operations_unchanged": False,
                "rollback_hash": baseline.phenotype_hash}, None

    validated = validate(problem, candidate, operator_index)
    before = dict(baseline.comparison_metrics)
    after = dict(validated.comparison_metrics)
    valid = (validated.status == CrafterStatus.VALIDATED_FEASIBLE and
             bool(validated.validation_report.get("valid")))
    score_replay = comparison_metrics(problem, validated)
    exported_one, exported_two = exported_rows(problem, validated), exported_rows(problem, validated)
    changed = [item.assignment.operation_key for item in validated.operations
               if item != baseline_by_key[item.assignment.operation_key]]
    machine_changes = [key for key in mutable if
                       baseline_by_key[key].assignment.line_id != cp_assignment[key]["line_id"] or
                       tuple(sorted(baseline_by_key[key].assignment.machine_ids)) != tuple(sorted(cp_assignment[key]["machine_ids"]))]
    k_changes = [key for key in mutable if baseline_by_key[key].assignment.machine_count != cp_assignment[key]["machine_count"]]
    line_changes = [key for key in mutable if baseline_by_key[key].assignment.line_id != cp_assignment[key]["line_id"]]
    worker_changes = [key for key in mutable if baseline_by_key[key].employee_ids != tuple(workers[key]["employees"])]
    churn = sum(abs(item.assignment.start_seconds-baseline_by_key[item.assignment.operation_key].assignment.start_seconds) +
                abs(item.assignment.end_seconds-baseline_by_key[item.assignment.operation_key].assignment.end_seconds)
                for item in validated.operations if item.assignment.operation_key in mutable)
    improved = valid and after["total_tardiness_seconds"] < before["total_tardiness_seconds"]
    diagnostics = {
        "accepted": bool(improved), "stage": "validated" if valid else "validator",
        "machine_verification_success": True, "worker_feasible": True,
        "outside_operations_unchanged": outside_unchanged,
        "validator_status": validated.status.value,
        "validator_valid": bool(validated.validation_report.get("valid")),
        "validator_report": validated.validation_report,
        "before": before, "after": after,
        "improvement_seconds": before["total_tardiness_seconds"]-after["total_tardiness_seconds"],
        "changed_operations": changed, "changed_operation_count": len(changed),
        "line_changes": line_changes, "line_change_count": len(line_changes),
        "k_changes": k_changes, "k_change_count": len(k_changes),
        "machine_changed_operations": machine_changes, "machine_change_count": len(machine_changes),
        "worker_changed_operations": worker_changes, "worker_change_count": len(worker_changes),
        "timing_churn_seconds": churn, "phenotype_hash": validated.phenotype_hash,
        "envelope_deltas": worker_result.get("envelope_deltas", {}),
        "rollback_hash": None if improved else baseline.phenotype_hash,
        "score_replay_equal": score_replay == after,
        "export_replay_equal": exported_one == exported_two,
    }
    return diagnostics, validated
