    skills = _sql(engine, "SELECT DISTINCT employee_id,operation_type FROM Operator_Skill_Matrix")
    bm = _sql(engine, "SELECT DISTINCT employee_id,batch_id FROM Batch_Members")
    eb = _sql(engine, "SELECT batch_id,line_id,is_active,rotation_offset,rest_day_offset FROM Employee_Batches")
    active_eb = eb[eb.is_active == 1]
    active_batch_members = bm.merge(active_eb[["batch_id", "line_id", "rotation_offset", "rest_day_offset"]], on="batch_id", how="inner")
    assign_ids = set(workers.employee_id.astype(int).unique())
    crew_ids = set(int(x) for x in index.get("crew_of", {}).keys())
    floater_index_ids = set(int(x) for x in index.get("shift_of", {}).keys())
    emp_ids = set(employees.employee_id.astype(int))
    latest_ids = set(latest.employee_id.astype(int))
    skill_ids = set(skills.employee_id.astype(int))
    active_batch_ids = set(active_batch_members.employee_id.astype(int))
