def _line_coverage(workers, index, engine):
    rows = []
    seen = set()
    for r in workers.itertuples(index=False):
        eid = int(r.employee_id)
        if eid not in index.get("crew_of", {}):
            continue
        line = r.line_id
        if pd.isna(line):
            continue
        key = (int(line), eid)
        if key in seen:
            continue
        seen.add(key)
        rot, rest = index["crew_of"][eid]
        band = shift_band_for_batch(rot, ORIGIN)[0]
        rows.append((int(line), band, eid, str(r.operation_type)))
    df = pd.DataFrame(rows, columns=["line_id", "band", "employee_id", "operation_type"]) if rows else pd.DataFrame(columns=["line_id", "band", "employee_id", "operation_type"])
    counts = df.groupby(["line_id", "band"]).employee_id.nunique().unstack(fill_value=0) if not df.empty else pd.DataFrame()
    active_lines = _sql(engine, "SELECT pl.line_id FROM Production_Lines pl WHERE pl.is_active=1").line_id.astype(int).tolist()
    coverage = []
    for line in sorted(set(active_lines) | set(df.line_id.tolist())):
        vals = {name: int(counts.loc[line, name]) if line in counts.index and name in counts.columns else 0 for name, _, _ in SHIFT_BANDS}
        n = sum(v > 0 for v in vals.values())
        coverage.append({"line_id": str(line), "counts": vals, "shift_count_with_workers": n, "category": f"{n}_SHIFT_COVERAGE"})
    return {"lines_audited": len(coverage), "coverage": coverage, "summary": dict(Counter(x["category"] for x in coverage)), "database_writes": 0}


