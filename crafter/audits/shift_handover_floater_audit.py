def _handover_feasibility(modes, workers, index, routing):
    # Pick deterministic selected-mode representatives: common skill,
    # scarce skill, longest elapsed operation, plus P2 when present.
    unique_workers = workers.drop_duplicates(["employee_id", "operation_type"]).copy()
    skill_counts = unique_workers.groupby("operation_type").employee_id.nunique().to_dict()
    flat = []
    for cell in modes:
        for key, mode in cell.get("selected", {}).items():
            op_id = int(str(key).split("_")[-1])
            flat.append((cell.get("label"), key, mode, str(routing.get(op_id, {}).get("required_machine_type"))))
    picks = []
    seen = set()
    if flat:
        common = max(flat, key=lambda x: (skill_counts.get(x[3], 0), x[1]))
        scarce = min(flat, key=lambda x: (skill_counts.get(x[3], 10**9), x[1]))
        longest = max(flat, key=lambda x: (float(x[2].get("elapsed_seconds", 0)), x[1]))
        for label, item in (("COMMON", common), ("SCARCE", scarce), ("LONG", longest)):
            if item[1] not in seen:
                picks.append((label, item)); seen.add(item[1])
        p2 = next((x for x in flat if x[1].startswith("1029_")), None)
        if p2 and p2[1] not in seen:
            picks.append(("P2", p2)); seen.add(p2[1])
    out = []
    for label, pick in picks[:4]:
        cell, key, mode, optype = pick
        if not mode or not key: continue
        line = int(mode.get("line_id"))
        start = ORIGIN + timedelta(seconds=int(mode.get("start_seconds", 0)))
        current_band = next((name for name, s, e in SHIFT_BANDS if band_covers((name, s, e), start)), "unknown")
        next_idx = (next((i for i, (name, _s, _e) in enumerate(SHIFT_BANDS) if name == current_band), 0) + 1) % len(SHIFT_BANDS)
        next_band = SHIFT_BANDS[next_idx][0]
        candidates = []
        for r in unique_workers[unique_workers.operation_type.astype(str) == optype].itertuples(index=False):
            if pd.isna(r.line_id) or int(r.line_id) != line: continue
            eid = int(r.employee_id)
            if eid in index.get("crew_of", {}):
                rot, rest = index["crew_of"][eid]
                if shift_band_for_batch(rot, start)[0] == next_band and operator_available_at(index, eid, start): candidates.append(eid)
        out.append({"label": label, "cell": cell, "operation_key": key, "operation_type": optype, "line_id": line, "current_band": current_band, "next_band": next_band, "current_workers": mode.get("worker_ids", []), "qualified_next_shift_workers": sorted(set(str(x) for x in candidates)), "incumbent_k": mode.get("machine_count"), "structurally_handover_feasible": bool(candidates), "non_authoritative": True})
    return {"representatives": out, "note": "Feasibility only; no replacement modes were generated and no scheduler state was changed.", "database_writes": 0}


def _all_worker_safety(index):
    worker_ids = sorted(set(index.get("crew_of", {})) | set(index.get("shift_of", {})), key=str)
    clock_points = [(0, 2, 0), (0, 5, 59), (0, 6, 0), (0, 8, 0), (0, 13, 59), (0, 14, 0), (0, 18, 0), (0, 21, 59), (0, 22, 0), (0, 23, 59)]
    checked = 0; h24 = []; no_avail = []; boundary = []; rest_fail = []; overnight_fail = []
    for eid in worker_ids:
        samples = []
        if eid in index.get("crew_of", {}):
            rot, rest = index["crew_of"][eid]
            for d in range(8):
                day = ORIGIN.date() + timedelta(days=d)
                for _, h, minute in clock_points:
                    when = datetime.combine(day, time(h, minute))
                    expected = False if day.weekday() == rest_weekday_for_batch(rest, day) else band_covers(shift_band_for_batch(rot, day), when)
                    actual = bool(operator_available_at(index, eid, when)); samples.append((when, expected, actual, day.weekday() == rest_weekday_for_batch(rest, day)))
        else:
            for d in range(2):
                day = ORIGIN.date() + timedelta(days=d)
                for _, h, minute in clock_points:
                    when = datetime.combine(day, time(h, minute)); samples.append((when, bool(operator_available_at(index, eid, when)), bool(operator_available_at(index, eid, when)), False))
        checked += 1
        if samples and all(a for _w, _e, a, _r in samples): h24.append(str(eid))
        if samples and not any(a for _w, _e, a, _r in samples): no_avail.append(str(eid))
        boundary.extend({"worker_id": str(eid), "when": w.isoformat(), "expected": e, "actual": a} for w, e, a, _r in samples if e != a)
        rest_fail.extend({"worker_id": str(eid), "when": w.isoformat()} for w, e, a, r in samples if r and a)
        if eid in index.get("crew_of", {}):
            overnight_fail.extend({"worker_id": str(eid), "when": w.isoformat()} for w, e, a, _r in samples if w.hour in (0, 2, 5) and a and shift_band_for_batch(index["crew_of"][eid][0], w)[0] != "Night" and w.hour < 6)
    return {"workers_tested": checked, "workers_with_24h_availability": len(h24), "workers_with_24h_sample": h24[:100], "workers_with_no_availability": len(no_avail), "boundary_failures": len(boundary), "boundary_failure_examples": boundary[:100], "rest_day_failures": len(rest_fail), "overnight_failures": len(overnight_fail), "clock_points": ["02:00", "05:59", "06:00", "08:00", "13:59", "14:00", "18:00", "21:59", "22:00", "23:59"], "calendar_safety_pass": not h24 and not boundary and not rest_fail and not overnight_fail, "database_writes": 0}


def _selected_calendar_audit(index, modes):
    checked = 0; violations = []
    for cell in modes:
        for key, mode in cell.get("selected", {}).items():
            segments = mode.get("worker_segments") or []
            for worker in mode.get("worker_ids", []):
                eid = int(worker) if str(worker).isdigit() else worker
                for pair in segments:
                    start = datetime.fromisoformat(str(pair[0])); end = datetime.fromisoformat(str(pair[1])); t = start
                    while t < end:
                        if not operator_available_at(index, eid, t): violations.append({"cell": cell.get("label"), "operation_key": key, "worker_id": str(worker), "segment": [start.isoformat(), end.isoformat()], "bad_instant": t.isoformat()})
                        checked += 1
                        t += timedelta(hours=1)
                    if end > start and not operator_available_at(index, eid, end - timedelta(seconds=1)):
                        violations.append({"cell": cell.get("label"), "operation_key": key, "worker_id": str(worker), "segment": [start.isoformat(), end.isoformat()], "bad_instant": (end - timedelta(seconds=1)).isoformat()})
    return {"segments_checked": checked, "violations": len(violations), "operations_affected": sorted(set(x["operation_key"] for x in violations)), "workers_affected": sorted(set(x["worker_id"] for x in violations)), "calendar_safe": not violations, "database_writes": 0}


def _pause_resume_and_machine_hold(modes):
    op_rows = []; gaps = []
    for cell in modes:
        for key, mode in cell.get("selected", {}).items():
            segs = [(datetime.fromisoformat(str(p[0])), datetime.fromisoformat(str(p[1]))) for p in mode.get("worker_segments", [])]
            if not segs: continue
            segs.sort(); gap_list = [(b[0] - a[1]).total_seconds() for a, b in zip(segs, segs[1:])]
            start, end = segs[0][0], segs[-1][1]
            row = {"cell": cell.get("label"), "operation_key": key, "worker_ids": mode.get("worker_ids", []), "segment_count": len(segs), "span_seconds": (end - start).total_seconds(), "productive_seconds": sum((b-a).total_seconds() for a,b in segs), "calendar_days": (end.date() - start.date()).days + 1, "max_worker_gap_seconds": max(gap_list or [0]), "spans_multiple_shift_windows": len(segs) > 1, "spans_multiple_days": start.date() != end.date()}
            op_rows.append(row); gaps.extend(gap_list)
    return {"operations_audited": len(op_rows), "operations_spanning_more_than_one_shift": sum(x["spans_multiple_shift_windows"] for x in op_rows), "operations_spanning_more_than_one_calendar_day": sum(x["spans_multiple_days"] for x in op_rows), "same_workers_resume_after_8h_gap": sum(x["max_worker_gap_seconds"] > 8*3600 for x in op_rows), "same_workers_resume_after_16h_gap": sum(x["max_worker_gap_seconds"] > 16*3600 for x in op_rows), "maximum_elapsed_operation_seconds": max((x["span_seconds"] for x in op_rows), default=0), "maximum_worker_inactivity_gap_seconds": max(gaps or [0]), "rows": op_rows, "database_writes": 0}


def _machine_hold(modes):
    rows = []
    for cell in modes:
        for key, mode in cell.get("selected", {}).items():
            occupancy = float(mode.get("machine_occupancy_end_seconds", 0)) - float(mode.get("machine_occupancy_start_seconds", 0))
            productive = float(mode.get("productive_seconds", 0)); setup = float(mode.get("setup_seconds", 0)); idle = max(0.0, occupancy - productive - setup)
            rows.append({"cell": cell.get("label"), "operation_key": key, "machine_occupancy_seconds": occupancy, "productive_worker_seconds": productive, "setup_seconds": setup, "machine_idle_held_seconds": idle, "idle_held_percentage": idle / occupancy if occupancy else 0.0})
    return {"operations_audited": len(rows), "total_machine_occupancy_seconds": sum(x["machine_occupancy_seconds"] for x in rows), "total_idle_held_seconds": sum(x["machine_idle_held_seconds"] for x in rows), "mean_idle_held_percentage": sum(x["idle_held_percentage"] for x in rows) / len(rows) if rows else 0, "rows": rows, "database_writes": 0}


def _counterfactual_handover(modes, index, workers, routing):
    # Non-authoritative diagnostic: only samples modes with a structurally
    # available next-shift same-line skilled worker.
    reps = []
    skill_df = workers.drop_duplicates(["employee_id", "operation_type"])
    for cell in modes:
        for key, mode in cell.get("selected", {}).items():
            if len(reps) >= 6: break
            if len(mode.get("worker_segments", [])) < 2: continue
            op_id = int(str(key).split("_")[-1]); optype = str(routing.get(op_id, {}).get("required_machine_type")); start = ORIGIN + timedelta(seconds=int(mode.get("machine_occupancy_start_seconds", 0)))
            current = next((i for i, (name,s,e) in enumerate(SHIFT_BANDS) if band_covers((name,s,e), start)), 0); nxt = SHIFT_BANDS[(current+1)%3][0]; line = int(mode.get("line_id")); possible = []
            for r in skill_df[skill_df.operation_type.astype(str) == optype].itertuples(index=False):
                if pd.isna(r.line_id) or int(r.line_id) != line: continue
                eid = int(r.employee_id)
                if eid in index.get("crew_of", {}) and shift_band_for_batch(index["crew_of"][eid][0], start)[0] == nxt: possible.append(eid)
            if not possible: continue
            current_end = datetime.fromisoformat(str(mode["worker_segments"][-1][1])); productive = float(mode.get("productive_seconds", 0)); setup = float(mode.get("setup_seconds", 0)); ideal_end = start + timedelta(seconds=setup + productive)
            reps.append({"cell": cell.get("label"), "operation_key": key, "operation_type": optype, "line_id": line, "current_end": current_end.isoformat(), "idealized_handover_end": ideal_end.isoformat(), "elapsed_reduction_seconds": max(0.0, (current_end - ideal_end).total_seconds()), "qualified_next_shift_worker_count": len(set(possible)), "next_shift": nxt, "classification": "NON_AUTHORITATIVE_DIAGNOSTIC"})
    return {"samples": reps, "note": "This does not generate modes or change CRAFT; it estimates continuous productive completion if a legal next-shift crew were allowed to hand over.", "database_writes": 0}


