def _handover_inventory(engine, schema):
    terms = re.compile(r"handover|worker|employee|operator|shift|resume|pause|quantity|wip|bundle|attendance|history|remaining|completed", re.I)
    table_hits = []
    for table, group in schema.groupby("TABLE_NAME"):
        cols = [str(x) for x in group.COLUMN_NAME.tolist()]
        matched = [x for x in cols if terms.search(x)]
        if matched:
            table_hits.append({"table": table, "matched_columns": matched, "all_columns": cols})
    code_hits = [
        {"path": "data_generation/simulation_calendar.py", "evidence": "explicit docstring/policy says no implicit handoffs; same worker resumes"},
        {"path": "data_generation/seed_database_fixed.py", "evidence": "synthetic seed creates one employee assignment per schedule row and fixed batch crews"},
        {"path": "utils/work_calendar.py", "evidence": "productive_segments pauses and resumes the same injected worker predicate"},
        {"path": "ga/worker_allocation.py", "evidence": "fixed-crew allocation; no handover transition"},
    ]
    return {"table_hits": table_hits, "code_hits": code_hits, "database_writes": 0}


