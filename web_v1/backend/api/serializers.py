from rest_framework import serializers

class FactorySerializer(serializers.Serializer):
    id = serializers.IntegerField()
    name = serializers.CharField()
    region = serializers.CharField()
    health = serializers.CharField()
    active_orders = serializers.IntegerField()
    running_operations = serializers.IntegerField()
    available_workers = serializers.IntegerField()
    worker_capacity = serializers.IntegerField()
    available_machines = serializers.IntegerField()
    machine_capacity = serializers.IntegerField()
    utilization = serializers.FloatField()
    risk = serializers.CharField()

class LineSerializer(serializers.Serializer):
    id = serializers.CharField()
    factory_id = serializers.IntegerField()
    name = serializers.CharField()
    active_order = serializers.CharField(allow_blank=True)
    operation = serializers.CharField(allow_blank=True)
    target = serializers.IntegerField()
    actual = serializers.IntegerField()
    workers = serializers.IntegerField()
    machines_available = serializers.IntegerField()
    status = serializers.CharField()

class OrderSerializer(serializers.Serializer):
    id = serializers.CharField()
    factory_id = serializers.IntegerField()
    factory_name = serializers.CharField()
    style = serializers.CharField()
    sku = serializers.CharField()
    quantity = serializers.IntegerField()
    smv = serializers.FloatField()
    release = serializers.DateTimeField()
    due = serializers.DateTimeField()
    progress = serializers.IntegerField()
    current_operation = serializers.CharField()
    priority = serializers.CharField()
    risk = serializers.CharField()
    status = serializers.CharField()
    line_id = serializers.CharField()

class MachineSerializer(serializers.Serializer):
    id = serializers.CharField()
    type = serializers.CharField()
    factory_id = serializers.IntegerField()
    line_id = serializers.CharField()
    status = serializers.CharField()
    current_operation = serializers.CharField(allow_blank=True)
    availability = serializers.IntegerField()

class WorkerSerializer(serializers.Serializer):
    id = serializers.CharField()
    display_name = serializers.CharField()
    factory_id = serializers.IntegerField()
    line_id = serializers.CharField()
    shift = serializers.CharField()
    skills = serializers.ListField(child=serializers.CharField())
    availability = serializers.CharField()
    current_operation = serializers.CharField(allow_blank=True)

class OperationSerializer(serializers.Serializer):
    id = serializers.CharField()
    order_id = serializers.CharField()
    factory_id = serializers.IntegerField()
    line_id = serializers.CharField()
    operation = serializers.CharField()
    machine_id = serializers.CharField()
    workers = serializers.ListField(child=serializers.CharField())
    worker_count = serializers.IntegerField()
    start = serializers.DateTimeField()
    end = serializers.DateTimeField()
    status = serializers.CharField()
    risk = serializers.CharField()
    predecessor = serializers.CharField(allow_blank=True)
    successor = serializers.CharField(allow_blank=True)
    release = serializers.DateTimeField()
    due = serializers.DateTimeField()
    smv = serializers.FloatField()

class DisruptionSerializer(serializers.Serializer):
    id = serializers.CharField()
    type = serializers.CharField()
    severity = serializers.CharField()
    occurred_at = serializers.DateTimeField()
    entity = serializers.CharField()
    factory_id = serializers.IntegerField()
    line_id = serializers.CharField(allow_blank=True)
    order_id = serializers.CharField(allow_blank=True)
    impact = serializers.CharField()
    status = serializers.CharField()
    craft_action = serializers.CharField()
    description = serializers.CharField()

class CraftRunSerializer(serializers.Serializer):
    id = serializers.CharField()
    factory_id = serializers.IntegerField()
    trigger = serializers.CharField()
    reference_time = serializers.DateTimeField()
    affected_region = serializers.CharField()
    operations_in_window = serializers.IntegerField()
    controller_status = serializers.CharField()
    cp_status = serializers.CharField()
    runtime_seconds = serializers.FloatField()
    configurations = serializers.IntegerField()
    regimes = serializers.IntegerField()
    recovery_rounds = serializers.IntegerField()
    changed_operations = serializers.ListField()
    accepted = serializers.BooleanField()
    materialization = serializers.CharField()
    replay = serializers.CharField()
    physical_validation = serializers.CharField()
    scope_validation = serializers.CharField()
    domain_exhausted = serializers.BooleanField()
    physical_infeasibility_proven = serializers.BooleanField()
    message = serializers.CharField()

